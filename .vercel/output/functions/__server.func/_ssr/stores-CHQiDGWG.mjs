function hostAllowed(store, raw) {
	try {
		const host = new URL(raw).hostname.replace(/^www\./, "");
		if (!store) return host.length > 0;
		return host === store.host || host.endsWith(`.${store.host}`);
	} catch {
		return false;
	}
}
