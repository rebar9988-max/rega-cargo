export type BundledKeyword = {
  category: string;
  keyword: string;
  language: ComplianceLang;
  level: KeywordLevel;
};

/** Flat list of every bundled keyword. */
export const BUNDLED_KEYWORDS: BundledKeyword[] = PROHIBITED.flatMap((cat) =>
  (Object.keys(cat.words) as ComplianceLang[]).flatMap((language) =>
    cat.words[language].map((raw) => ({
      category: cat.slug,
      keyword: raw.replace(/^\?/, ""),
      language,
      level: (raw.startsWith("?") ? "review" : "block") as KeywordLevel,
    })),
  ),
);

